import crypto from "node:crypto";
import fsp from "node:fs/promises";
import path from "node:path";
import { writeAtomic } from "../atomic.js";
import { assistantHome } from "./workspace.js";

// Plumbing for the approval gate (phase 18):
// - per-turn hook tokens (in memory; a server restart kills them, so an orphaned
//   Claude process can't take outward actions),
// - the hook script Claude Code runs on every tool call (it forwards the call to
//   the Tethr server and fails CLOSED if the server can't be reached),
// - the per-turn --settings file (hooks, deny rules, Claude auto-memory off).

export interface HookTokenContext {
  companyId: string;
  threadId: string;
  runId: string;
}

const tokens = new Map<string, HookTokenContext & { expiresAt: number | null }>();

export function issueHookToken(ctx: HookTokenContext): string {
  const token = crypto.randomBytes(24).toString("base64url");
  tokens.set(token, { ...ctx, expiresAt: null });
  return token;
}

/** Revoke a token shortly after its turn ends (a late PostToolUse may still arrive). */
export function revokeHookToken(token: string, afterMs = 30_000) {
  const entry = tokens.get(token);
  if (!entry) return;
  entry.expiresAt = Date.now() + afterMs;
  setTimeout(() => tokens.delete(token), afterMs).unref?.();
}

export function resolveHookToken(token: string | undefined | null): HookTokenContext | null {
  if (!token) return null;
  const entry = tokens.get(token);
  if (!entry) return null;
  if (entry.expiresAt !== null && entry.expiresAt < Date.now()) {
    tokens.delete(token);
    return null;
  }
  return { companyId: entry.companyId, threadId: entry.threadId, runId: entry.runId };
}

export const HOOK_SOURCE = `// Tethr approval gate hook (generated by the Tethr server; do not edit).
// Forwards Claude Code's PreToolUse/PostToolUse payload to Tethr and relays
// the decision. Pre fails CLOSED if Tethr can't be reached.
const phase = process.argv[2] === "post" ? "post" : "pre";
const base = (process.env.TETHR_HOOK_URL || process.env.PAPERCLIP_API_URL || "http://localhost:3100").replace(/\\/$/, "");
const token = process.env.TETHR_HOOK_TOKEN || "";
let raw = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (c) => { raw += c; });
process.stdin.on("end", async () => {
  try {
    const res = await fetch(base + "/api/tethr/hooks/" + phase, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: "Bearer " + token },
      body: raw || "{}",
      signal: AbortSignal.timeout(25000),
    });
    const out = await res.json();
    if (out && typeof out.stdout === "string") process.stdout.write(out.stdout);
    if (out && typeof out.stderr === "string") process.stderr.write(out.stderr);
    process.exit(out && Number.isInteger(out.exitCode) ? out.exitCode : phase === "pre" ? 2 : 0);
  } catch (e) {
    if (phase === "pre") {
      process.stderr.write("Tethr approval gate: Tethr isn't reachable, so this action was blocked.");
      process.exit(2);
    }
    process.exit(0);
  }
});
`;

/** Write the hook script (content-addressed, so an upgrade never edits a running copy). */
export async function ensureHookScript(): Promise<string> {
  const hash = crypto.createHash("sha256").update(HOOK_SOURCE).digest("hex").slice(0, 12);
  const dir = path.join(assistantHome(), "hooks");
  const file = path.join(dir, `tethr-gate-${hash}.mjs`);
  await fsp.mkdir(dir, { recursive: true });
  try {
    await fsp.access(file);
  } catch {
    await fsp.writeFile(file, HOOK_SOURCE, "utf8");
  }
  return file;
}

function shellQuote(s: string): string {
  return `"${s.replace(/(["\\$`])/g, "\\$1")}"`;
}

/** Build the per-turn settings JSON (hooks, deny rules, no auto-memory). */
export function buildSettings(opts: { nodePath: string; hookScript: string; deny: string[] }) {
  const cmd = (phase: "pre" | "post") => `${shellQuote(opts.nodePath)} ${shellQuote(opts.hookScript)} ${phase}`;
  return {
    autoMemoryEnabled: false,
    permissions: { deny: [...new Set(opts.deny)] },
    hooks: {
      PreToolUse: [{ matcher: ".*", hooks: [{ type: "command", command: cmd("pre"), timeout: 30 }] }],
      PostToolUse: [{ matcher: ".*", hooks: [{ type: "command", command: cmd("post"), timeout: 30 }] }],
    },
  };
}

export async function writeSettingsFile(companyId: string, settings: unknown): Promise<string> {
  const file = path.join(assistantHome(), "settings", `settings-${companyId}.json`);
  await writeAtomic(file, JSON.stringify(settings, null, 2));
  return file;
}
