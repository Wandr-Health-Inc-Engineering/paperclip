import crypto from "node:crypto";
import fsp from "node:fs/promises";
import path from "node:path";
import { TETHR_TOOLS_SERVER } from "./tethr-tools.js";
import { assistantHome } from "./workspace.js";

// How the chat's Claude session reaches Tethr's own tools (phase 19). Each turn
// passes `--mcp-config <file>` naming one stdio MCP server, "tethr": this tiny
// zero-dependency bridge. It speaks MCP JSON-RPC on stdin/stdout and forwards
// tools/list and tools/call to the Tethr server with the turn's hook token, so
// the work (and the API keys) stay in the server. The approval gate still sees
// every call (PreToolUse fires for MCP tools like any other).

export const BRIDGE_SOURCE = `// Tethr tools bridge (generated by the Tethr server; do not edit).
// A minimal MCP stdio server that forwards tools/list and tools/call to Tethr.
const base = (process.env.TETHR_HOOK_URL || "http://localhost:3100").replace(/\\/$/, "");
const token = process.env.TETHR_HOOK_TOKEN || "";
const send = (msg) => process.stdout.write(JSON.stringify(msg) + "\\n");
async function post(op, body, ms) {
  const res = await fetch(base + "/api/tethr/assistant/tools/" + op, {
    method: "POST",
    headers: { "content-type": "application/json", authorization: "Bearer " + token },
    body: JSON.stringify(body || {}),
    signal: AbortSignal.timeout(ms),
  });
  const out = await res.json().catch(() => null);
  if (!res.ok) throw new Error((out && out.error) || "Tethr returned " + res.status);
  return out || {};
}
async function handle(line) {
  let msg;
  try { msg = JSON.parse(line); } catch { return; }
  if (!msg || typeof msg !== "object") return;
  const { id, method, params } = msg;
  const hasId = id !== undefined && id !== null;
  const reply = (result) => { if (hasId) send({ jsonrpc: "2.0", id, result }); };
  const fail = (code, message) => { if (hasId) send({ jsonrpc: "2.0", id, error: { code, message } }); };
  try {
    if (method === "initialize") {
      return reply({
        protocolVersion: (params && params.protocolVersion) || "2025-06-18",
        capabilities: { tools: {} },
        serverInfo: { name: "tethr", version: "1.0.0" },
      });
    }
    if (method === "ping") return reply({});
    if (method === "tools/list") {
      const out = await post("list", {}, 15000);
      return reply({ tools: Array.isArray(out.tools) ? out.tools : [] });
    }
    if (method === "tools/call") {
      const out = await post("call", { name: params && params.name, arguments: (params && params.arguments) || {} }, 600000);
      return reply({ content: Array.isArray(out.content) ? out.content : [{ type: "text", text: "" }], isError: out.isError === true });
    }
    if (!hasId) return; // a notification (e.g. notifications/initialized)
    return fail(-32601, "Method not found: " + method);
  } catch (e) {
    const message = (e && e.message) || String(e);
    if (method === "tools/call") return reply({ content: [{ type: "text", text: "Tethr tools: " + message }], isError: true });
    return fail(-32603, message);
  }
}
let buf = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => {
  buf += chunk;
  let i;
  while ((i = buf.indexOf("\\n")) >= 0) {
    const line = buf.slice(0, i).trim();
    buf = buf.slice(i + 1);
    if (line) void handle(line);
  }
});
process.stdin.on("end", () => process.exit(0));
`;

/** Write the bridge script (content-addressed, so an upgrade never edits a running copy). */
export async function ensureToolsBridge(): Promise<string> {
  const hash = crypto.createHash("sha256").update(BRIDGE_SOURCE).digest("hex").slice(0, 12);
  const dir = path.join(assistantHome(), "hooks");
  const file = path.join(dir, `tethr-tools-${hash}.mjs`);
  await fsp.mkdir(dir, { recursive: true });
  try {
    await fsp.access(file);
  } catch {
    await fsp.writeFile(file, BRIDGE_SOURCE, "utf8");
  }
  return file;
}

export function buildMcpConfig(opts: { nodePath: string; bridgeScript: string; token: string; url: string }) {
  return {
    mcpServers: {
      [TETHR_TOOLS_SERVER]: {
        type: "stdio",
        command: opts.nodePath,
        args: [opts.bridgeScript],
        env: { TETHR_HOOK_TOKEN: opts.token, TETHR_HOOK_URL: opts.url },
      },
    },
  };
}

/** The per-turn MCP config (it holds the turn's token: owner-only, removed after the turn). */
export async function writeMcpConfig(runId: string, config: unknown): Promise<string> {
  const dir = path.join(assistantHome(), "mcp");
  await fsp.mkdir(dir, { recursive: true, mode: 0o700 });
  const safe = runId.replace(/[^A-Za-z0-9-]/g, "");
  const file = path.join(dir, `mcp-${safe}.json`);
  await fsp.writeFile(file, JSON.stringify(config, null, 2), { encoding: "utf8", mode: 0o600 });
  return file;
}

export async function removeMcpConfig(file: string | null | undefined): Promise<void> {
  if (file) await fsp.unlink(file).catch(() => {});
}
